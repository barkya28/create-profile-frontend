-- Create views for dashboard data
CREATE OR REPLACE VIEW v_overall_dashboard AS
SELECT 
    COUNT(DISTINCT u.user_id) as total_users,
    COUNT(DISTINCT s.game_name) as total_games,
    COUNT(s.score_id) as total_scores,
    NVL(MAX(s.score), 0) as highest_score,
    NVL(AVG(s.score), 0) as average_score
FROM users u
LEFT JOIN scores s ON u.user_id = s.user_id;

CREATE OR REPLACE VIEW v_weekly_dashboard AS
SELECT 
    COUNT(DISTINCT u.user_id) as weekly_users,
    COUNT(DISTINCT s.game_name) as weekly_games,
    COUNT(s.score_id) as weekly_scores,
    NVL(MAX(s.score), 0) as weekly_highest_score,
    NVL(AVG(s.score), 0) as weekly_average_score
FROM users u
LEFT JOIN scores s ON u.user_id = s.user_id
WHERE s.created_at >= TRUNC(SYSDATE) - 7;

-- Create view for top scores
CREATE OR REPLACE VIEW v_top_scores AS
SELECT 
    u.name,
    u.mobile_no,
    s.game_name,
    s.score,
    s.created_at,
    RANK() OVER (PARTITION BY s.game_name ORDER BY s.score DESC) as rank_in_game
FROM users u
JOIN scores s ON u.user_id = s.user_id
ORDER BY s.game_name, s.score DESC;

