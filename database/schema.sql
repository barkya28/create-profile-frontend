-- Users table
CREATE TABLE users (
    user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile_no VARCHAR2(15) NOT NULL UNIQUE,
    name VARCHAR2(100) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    is_active NUMBER(1) DEFAULT 1,
    CONSTRAINT chk_mobile_format CHECK (REGEXP_LIKE(mobile_no, '^[0-9]{10}$'))
);

-- OTPs table for temporary OTP storage
CREATE TABLE otps (
    otp_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mobile_no VARCHAR2(15) NOT NULL,
    otp_code VARCHAR2(10) NOT NULL,
    expiry_time TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    is_used NUMBER(1) DEFAULT 0,
    CONSTRAINT chk_otp_mobile_format CHECK (REGEXP_LIKE(mobile_no, '^[0-9]{10}$'))
);

-- Scores table
CREATE TABLE scores (
    score_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    score NUMBER NOT NULL,
    game_name VARCHAR2(100) NOT NULL,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT fk_scores_user_id FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_score_positive CHECK (score >= 0)
);

-- Games table (for tracking different games)
CREATE TABLE games (
    game_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_name VARCHAR2(100) NOT NULL UNIQUE,
    description VARCHAR2(500),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    is_active NUMBER(1) DEFAULT 1
);

-- User sessions table (for tracking user sessions)
CREATE TABLE user_sessions (
    session_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    session_token VARCHAR2(255) NOT NULL UNIQUE,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    is_active NUMBER(1) DEFAULT 1,
    CONSTRAINT fk_sessions_user_id FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE
);

-- Create indexes for better performance
CREATE INDEX idx_users_mobile ON users(mobile_no);
CREATE INDEX idx_otps_mobile ON otps(mobile_no);
CREATE INDEX idx_otps_expiry ON otps(expiry_time);
CREATE INDEX idx_scores_user_id ON scores(user_id);
CREATE INDEX idx_scores_created_at ON scores(created_at);
CREATE INDEX idx_scores_game_name ON scores(game_name);
CREATE INDEX idx_sessions_token ON user_sessions(session_token);
CREATE INDEX idx_sessions_user_id ON user_sessions(user_id);

-- Create triggers for updated_at timestamp
CREATE OR REPLACE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW
BEGIN
    :NEW.updated_at := SYSTIMESTAMP;
END;
/

-- Create a procedure to clean expired OTPs (to be called periodically)
CREATE OR REPLACE PROCEDURE clean_expired_otps AS
BEGIN
    DELETE FROM otps WHERE expiry_time <= SYSTIMESTAMP;
    COMMIT;
END;
/

-- Create a procedure to clean expired sessions
CREATE OR REPLACE PROCEDURE clean_expired_sessions AS
BEGIN
    DELETE FROM user_sessions WHERE expires_at <= SYSTIMESTAMP;
    COMMIT;
END;
/

